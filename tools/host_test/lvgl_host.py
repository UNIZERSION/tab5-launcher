"""LVGL 9.3 on the PC with the firmware's own LVGL options (build/config/sdkconfig.h, without FreeRTOS),
shared by ui_shots.py (screen snapshots) and run.py (font RLE test). The objects are kept in
%TEMP%/l5_ui_lvgl. lv_font_fmt_txt.c is built twice: as LVGL ships it and as the launcher builds it
(tools/patch_lvgl_rle.py: RLE state per call).
"""
import concurrent.futures
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.abspath(os.path.join(HERE, '..', '..'))
LVGL = os.path.join(PROJECT, 'managed_components', 'lvgl__lvgl')
FONT_TXT = os.path.join(LVGL, 'src', 'font', 'lv_font_fmt_txt.c')


def compiler():
    return os.environ.get('CC', 'zig cc' if shutil.which('zig') else 'gcc').split()


def host_sdkconfig():
    """the firmware's CONFIG_LV_* options, without FreeRTOS and with one draw unit"""
    src = os.path.join(PROJECT, 'build', 'config', 'sdkconfig.h')
    if not os.path.exists(src):
        sys.exit('build/config/sdkconfig.h missing: build the firmware once')
    out = ['/* generated by tools/host_test/lvgl_host.py from build/config/sdkconfig.h */\n']
    for line in open(src, encoding='utf-8'):
        if not line.startswith('#define CONFIG_LV_'):
            continue
        name = line.split()[1]
        if name == 'CONFIG_LV_OS_FREERTOS':
            continue
        if name == 'CONFIG_LV_DRAW_SW_DRAW_UNIT_CNT':
            line = '#define CONFIG_LV_DRAW_SW_DRAW_UNIT_CNT 1\n'
        out.append(line)
    out.append('#define CONFIG_LV_OS_NONE 1\n')
    return ''.join(out)


def run_all(jobs):
    errors = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        for cmd, r in zip(jobs, ex.map(lambda c: subprocess.run(c, capture_output=True, text=True), jobs)):
            if r.returncode:
                errors.append(' '.join(cmd[-3:]) + '\n' + r.stdout + r.stderr)
    if errors:
        sys.exit('\n'.join(errors[:5]))


def build(cc):
    """compiles what is stale; returns (flags, LVGL objects without lv_font_fmt_txt, its object as shipped,
    its object as patched)"""
    cache = os.path.join(tempfile.gettempdir(), 'l5_ui_lvgl')
    os.makedirs(cache, exist_ok=True)
    conf = host_sdkconfig()
    conf_path = os.path.join(cache, 'host_sdkconfig.h')
    stamp = hashlib.sha1((conf + ' '.join(cc)).encode()).hexdigest()
    if not os.path.exists(conf_path) or open(conf_path, encoding='utf-8').read() != conf or \
            not os.path.exists(os.path.join(cache, stamp)):
        for f in os.listdir(cache):
            os.remove(os.path.join(cache, f))
        open(conf_path, 'w', encoding='utf-8').write(conf)
        open(os.path.join(cache, stamp), 'w').close()
    flags = cc + ['-std=gnu11', '-O1', '-w', '-I' + cache, '-I' + LVGL,
                  '-DLV_CONF_KCONFIG_EXTERNAL_INCLUDE="host_sdkconfig.h"']

    def stale(obj, src):
        return not os.path.exists(obj) or os.path.getmtime(obj) < os.path.getmtime(src)

    objs, jobs, shipped = [], [], None
    for root, _, files in os.walk(os.path.join(LVGL, 'src')):
        for f in files:
            if f.endswith('.c'):
                src = os.path.join(root, f)
                obj = os.path.join(cache, os.path.relpath(src, LVGL).replace(os.sep, '_')[:-2] + '.o')
                if os.path.samefile(src, FONT_TXT):
                    shipped = obj
                else:
                    objs.append(obj)
                if stale(obj, src):
                    jobs.append(flags + ['-c', src, '-o', obj])
    patched_src = os.path.join(cache, 'l5_patched_lv_font_fmt_txt.c')
    subprocess.check_call([sys.executable, os.path.join(PROJECT, 'tools', 'patch_lvgl_rle.py'), FONT_TXT, patched_src])
    patched = os.path.join(cache, 'l5_patched_lv_font_fmt_txt.o')
    if stale(patched, patched_src):
        jobs.append(flags + ['-c', patched_src, '-o', patched])
    print(f'LVGL: {len(jobs)} of {len(objs) + 2} files to compile', flush=True)
    run_all(jobs)
    return flags, objs, shipped, patched


def link(cc, exe, objs, work):
    rsp = os.path.join(work, os.path.basename(exe) + '.rsp')  # 400+ objects: longer than a Windows command line
    with open(rsp, 'w') as f:
        f.write('\n'.join('"' + o.replace('\\', '/') + '"' for o in objs) + '\n')
    subprocess.check_call(cc + ['-o', exe, '@' + rsp, '-lm'])
